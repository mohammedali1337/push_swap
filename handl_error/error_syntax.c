int error_syntax(char *str)
{
    int i;
    
    i = 1;
    if (!(str[0] == '+' || str[0] == '-' || (str[0] >= '0' && str[0] <= '9')))
        return (1);
    if ((str[0] == '+' || str[0] == '-' && !(str[1] >= '0' && str[1] <= '9')))
        return (1);
    while (str[i])
    {
        if (!(str[i] >= '0' && str[i] <= '9'))
            return (1);
        i++;
    }
    return (0);
    
}